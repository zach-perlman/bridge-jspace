"""The write-up's examples are the items Dan read (Dan 29 Oct 11:45, verify_prep_1145 item 6): `make examples-render
SEED=29` writes examples/review-seed-<seed>/ from the views file's fixed sample (the same seed, never re-drawn): per
tier-1 view its items as review cards (index.html) and as text (examples.md: the prompt as the model saw it, the
decisive arms' top tokens and labels, Dan's mark where there is one), and a source.json the examples index lists.
CPU only; reads results/ and review/marks.jsonl.
"""

from __future__ import annotations

import json
from pathlib import Path

from bridge_jspace.review import checks as C
from bridge_jspace.review import fixed as F
from bridge_jspace.review import handcheck as H
from bridge_jspace.review import items as I
from bridge_jspace.review import page as P

MARKS = I.REPO / "review" / "marks.jsonl"


def picked(seed: int) -> list[tuple[dict, list[tuple[dict, str]]]]:
    """Per tier-1 view, its fixed sample's items in the views file's order, with their strata."""
    out = []
    for v in F.tier1():
        got = F.samples(v, seed, list(I.spec()["models"])) or {}
        by_id = {s["items"][0]["id"]: (s["items"][0], s["stratum"]) for ss in got.values() for s in ss}
        order = [e["item"] for e in F.fixed(v["id"], seed) or []]
        out.append((v, [by_id[i] for i in order if i in by_id]))
    return out


def item_md(it: dict, why: str, mark: dict | None) -> list[str]:
    v, m, w = I.view(it["view"]), it["model"], it["reader"]
    rd = it["case"]["readers"][w]
    tk = C.tokenizer(m)
    sfx = tk.decode(C.read_suffix(it), skip_special_tokens=False)
    out = [f"#### {I.spec()['models'][m]['label']} · {I.READER_NAME[w]} · `{it['scene']}`", "", f"_{why}_", "",
           f"Original prompt, as the model read it (the run appended {sfx!r} at the read):", "", "```",
           tk.decode(rd["ids"]["org"], skip_special_tokens=False) + sfx, "```", "",
           f"Changed prompt: {P.marked(it['case']['cf_context'], it['case']['context']).replace('<mark>', '**').replace('</mark>', '**')}", "",
           f"Answers: original {rd['answer']}, changed {rd['cf_answer']}.", "", "| arm | top token | the run's label |", "|---|---|---|"]  # fmt: skip
    for label in v.get("decisive") or list(it["rows"][w]):
        r = it["rows"][w].get(label)
        if r is None:
            continue
        top = repr(C.top_text(m, r["top"])) if r.get("top") is not None else "not stored"
        lab = P.stored_label(it, w, r)
        out.append(
            f"| {P.arm_name(it, label)} | {top} | {P.PLAIN.get(lab, lab)}{f' ({lab})' if lab in ('A', 'b') else ''} |"
        )
    out += ["", f"Dan's mark: **{mark['verdict']}**" + (f" ({mark['note']})" if mark.get("note") else "") if mark
            else "Dan's mark: not marked yet.", ""]  # fmt: skip
    return out


def export(seed: int, root: Path) -> Path:
    out = root / f"review-seed-{seed}"
    out.mkdir(parents=True, exist_ok=True)
    marks = {r["item"]: r for r in H.load_marks(MARKS) if r.get("seed") == seed}
    groups, cards, md = [], [], [f"# The items Dan read (seed {seed})", "",
                                 "The fixed sample of docs/review_views.yaml (fixed_sample), per headline claim; the same "
                                 "items as review/seed-<seed>/ and docs/verify_pack.md. Generated by `make examples-render "
                                 f"SEED={seed}`.", ""]  # fmt: skip
    n = 0
    for v, its in picked(seed):
        groups.append({"title": v["title"], "n_total": len(its)})
        cards.append(f"<h2>{P.E(v['title'])}</h2>")
        md += [f"## {v['title']}", ""]
        for it, why in its:
            n += 1
            cards.append(f"<p class='mut'>{P.E(why)}</p>" + P.card(it, seed, False, marks.get(it["id"])))
            md += item_md(it, why, marks.get(it["id"]))
    (out / "index.html").write_text(P.page(f"The items Dan read (seed {seed})", "".join(cards), False, ""))
    (out / "examples.md").write_text("\n".join(md) + "\n")
    entry = {"title": f"The items Dan read: the headline claims' fixed sample (seed {seed})", "n_examples": n,
             "groups": groups, "meta": f"seed {seed}; docs/review_views.yaml fixed_sample; marks from review/marks.jsonl"}  # fmt: skip
    (out / "source.json").write_text(json.dumps({"entry": entry}, indent=2))
    return out
