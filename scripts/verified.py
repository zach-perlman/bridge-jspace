"""VERIFIED.md's hand-check section, generated from Dan's marks (Dan 29 Oct 11:45, jobs/c3/batch53.yaml verify_prep_1145
item 5): per claim (tier-1 view), the items of the fixed sample read, consistent / wrong / unclear, the stop rule,
whether the automatic checks passed and whether the independent recount matched, and Dan's notes on the wrong and
unclear items. The tool, run by Dan after his marks: agents do not run it on VERIFIED.md (AGENTS.md: a claim is verified
only once a human puts it there).

Only the block between the BEGIN / END markers is written; the rest of VERIFIED.md is kept byte for byte. The inspector's
J-space notes in review/marks.jsonl ("kind": "jspace", no verdict) are skipped.

make review-verified                                    # after the marks: review/marks.jsonl -> VERIFIED.md
uv run python scripts/verified.py --out /tmp/V.md       # anywhere else (a dry run)
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from bridge_jspace.review import handcheck as H
from bridge_jspace.review import items as I

BEGIN = "<!-- generated by make review-verified (scripts/verified.py): BEGIN; edit the marks, not this block -->"
END = "<!-- generated by make review-verified: END -->"


def readme_claim(v: dict) -> str:
    """The claim's README rows (Claims table numbers) or its first README quote, for the table."""
    rows = v.get("readme_rows") or []
    return (
        f"README claims row{'s' if len(rows) > 1 else ''} {', '.join(map(str, rows))}" if rows else v.get("readme", "")
    )


def block(marks_path: Path, checks: dict | None, indep: dict | None) -> str:
    marks = H.load_marks(marks_path)
    pv = H.per_view(marks)
    fs = I.spec().get("fixed_sample") or {}
    sha = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=I.REPO, capture_output=True, text=True
    ).stdout.strip()
    views = {v["id"]: v for v in I.spec()["views"]}
    L = [BEGIN, "", f"## Hand check of the headline claims (seed {fs.get('seed')}, {fs.get('n_per_view')} items per claim)", "",
         f"Generated at {sha}, {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}, from {marks_path.name} ({len(marks)} "
         f"verdict marks), review/verify_checks.json ({(checks or {}).get('generated_utc', 'not run')}) and "
         "review/verify_independent.json. The items are docs/review_views.yaml's fixed_sample; the last mark per item "
         f"counts; a claim with {H.STOP_WRONG} or more items marked wrong is flagged (Dan's stop rule). How each was "
         "read: docs/verify_pack.md.", "",
         "| claim | what it says | items read | consistent | wrong | unclear | flagged | automatic checks | independent recount |",
         "|---|---|---|---|---|---|---|---|---|"]  # fmt: skip
    notes = []
    for vid, x in pv.items():
        a, b = H.auto_status(vid, checks, indep)
        L.append(f"| {x['order']}. {vid} | {views[vid]['title'].split('. ', 1)[-1]} ({readme_claim(views[vid])}) | "
                 f"{x['read']} of {x['sample']} | {x['consistent']} | {x['wrong']} | {x['unclear']} | "
                 f"{'yes' if x['flagged'] else 'no'} | {a} | {b} |")  # fmt: skip
        notes += [f"- {x['order']}. {vid}, `{r['item']}`: **{r['verdict']}** ({r.get('utc', '')}, commit {r.get('commit', '')}): "
                  f"{r.get('note', '') or '(no note)'}" for r in x["notes"]]  # fmt: skip
    L += ["", "Wrong and unclear items, with the notes:", "", *(notes or ["None."]), "", END]
    return "\n".join(L) + "\n"


def write(out: Path, text: str) -> None:
    old = out.read_text() if out.exists() else ""
    if BEGIN in old and END in old:
        head, rest = old.split(BEGIN, 1)
        new = head + text.rstrip("\n") + rest.split(END, 1)[1]
    else:
        new = old.rstrip("\n") + ("\n\n" if old else "") + text
    out.write_text(new)


def main(argv: list[str] | None = None) -> Path:
    ap = argparse.ArgumentParser()
    ap.add_argument("--marks", type=Path, default=I.REPO / "review" / "marks.jsonl")
    ap.add_argument("--out", type=Path, default=I.REPO / "VERIFIED.md")
    a = ap.parse_args(argv)
    checks = H.read_json(I.REPO / "review" / "verify_checks.json")
    indep = H.read_json(I.REPO / "review" / "verify_independent.json")
    write(a.out, block(a.marks, checks, indep))
    print(f"wrote the hand-check section of {a.out}")
    return a.out


if __name__ == "__main__":
    main()
