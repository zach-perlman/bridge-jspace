"""Render docs/plans/hypotheses.md from docs/plans/hypotheses.template.md: every number read from its data file by key, printed as
the READMEs print it, with its src comment. Markers: {{b|key}} / {{bci|key}} docs/breadth/data.csv (report_breadth.fmt),
{{x|key}} docs/depth/x0_numbers.json, {{s|model|quantity}} data/figures/depth/data.csv (2 decimals)."""

import csv
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
from scripts import readme_root as RR  # noqa: E402
from scripts.report_breadth import fmt  # noqa: E402

TEMPLATE = REPO / "docs" / "plans" / "hypotheses.template.md"
OUT = REPO / "docs" / "plans" / "hypotheses.md"


def breadth_rows() -> dict[str, dict]:
    rows = {}
    with (REPO / "docs/breadth/data.csv").open() as f:
        for r in csv.DictReader(f):
            num = lambda s: float(s) if s not in ("", None) else ""  # noqa: E731
            rows[r["key"]] = {"value": float(r["value"]), "lo": num(r["lo"]), "hi": num(r["hi"]), "unit": r["unit"]}
    return rows


B, X, S = breadth_rows(), RR.x0(), RR.story()
missing = []


def sub(m: re.Match) -> str:
    kind, *args = m.group(1).split("|")
    if kind in ("b", "bci"):
        if args[0] not in B:
            missing.append(m.group(0))
            return "??"
        return f"{fmt(B[args[0]], kind == 'bci')}<!-- src: docs/breadth/data.csv | {args[0]} -->"
    if kind == "x":
        if args[0] not in X:
            missing.append(m.group(0))
            return "??"
        return f"{X[args[0]]}<!-- src: docs/depth/x0_numbers.json | {args[0]} -->"
    if kind == "s":
        model, quantity = args[0], "|".join(args[1:])
        if (model, quantity) not in S:
            missing.append(m.group(0))
            return "??"
        return f"{S[(model, quantity)]:.2f}<!-- src: data/figures/depth/data.csv | {quantity} -->"
    missing.append(m.group(0))
    return "??"


text = re.sub(r"\{\{([^}]+)\}\}", sub, TEMPLATE.read_text())
if missing:
    sys.exit(f"unresolved markers: {missing}")
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("<!-- Generated by scripts/hypotheses_build.py from docs/plans/hypotheses.template.md; edit the template. "
               "Numbers rendered from docs/breadth/data.csv, docs/depth/x0_numbers.json and data/figures/depth/data.csv by key; each carries its src comment. -->\n" + text)
print(f"wrote {OUT.relative_to(REPO)}: {text.count('<!-- src:')} sourced numbers")
