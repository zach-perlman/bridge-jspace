"""verify_kit (Zach, 2026-10-26): material for a human check of a headline knock-out (VERIFIED.md is human-only).
For each run: an independent recompute of M - K (a few lines of plain Python over rows.jsonl, not jsuite2_score), and
20 random items (seed 0; 10 memory finals, 10 stated-fact finals) with their full prompt text, the expected answer, and
whether the model got it right unedited and under the J++ removal.

python scripts/verify_kit.py RUN:SET [RUN:SET ...]  ->  docs/verify_kit.md
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

RECOMPUTE = '''```python
import json
run, set_ = "{run}", "{set}"
items = {{json.loads(l)["id"]: json.loads(l) for l in open(f"data/tasks_v2/{{set_}}/items.jsonl")}}
rows = [json.loads(l) for l in open(f"results/ablate_v2/{{run}}/rows.jsonl")]
rows = [r for r in rows if r["kind"] == "clean" and items[r["id"]].get("module") == "facts" and items[r["id"]]["start"] in "PMT"]
ok = {{r["id"] for r in rows if r["condition"] == "none" and r["correct"]}}          # right unedited
def lost(final, cond="paper10"):
    sel = [r["correct"] for r in rows if r["condition"] == cond and r["id"] in ok and items[r["id"]]["final"] == final]
    return 100 * (1 - sum(sel) / len(sel)), len(sel)
(m, nm), (k, nk) = lost("M"), lost("K")
print(f"M lost {{m:.1f}} (n {{nm}}), K lost {{k:.1f}} (n {{nk}}), M - K {{m - k:+.1f}}")
```'''


def main(specs: list[str]) -> None:
    out = ["# Verification kit (generated by scripts/verify_kit.py; for Zach and Dan to check by hand, then record in VERIFIED.md)", ""]
    for spec in specs:
        run, set_ = spec.split(":")
        items = {json.loads(line)["id"]: json.loads(line) for line in (ROOT / "data" / "tasks_v2" / set_ / "items.jsonl").read_text().splitlines()}
        rows = [json.loads(line) for line in (ROOT / "results" / "ablate_v2" / run / "rows.jsonl").read_text().splitlines()]
        by = {(r["id"], r["condition"]): r for r in rows if r["kind"] == "clean"}
        ok = [i for (i, c), r in by.items() if c == "none" and r["correct"] and items[i].get("module") == "facts" and items[i]["start"] in "PMT"]
        rng = random.Random(0)
        pick = rng.sample(sorted(i for i in ok if items[i]["final"] == "M"), 10) + rng.sample(sorted(i for i in ok if items[i]["final"] == "K"), 10)
        out += [f"## {run} ({set_})", "", "**1. Recompute M - K yourself** (from the repo root on the GPU box; compare with docs/digest.md):", "",
                RECOMPUTE.format(run=run, set=set_), "", "**2. Check 20 random items** (10 memory finals M, 10 stated-fact finals K; all right unedited).",
                "For each: is the expected answer correct? Does a K item state the fact in the passage, and an M item not? "
                "Did the removal change the answer as the table says?", ""]  # fmt: skip
        for n, i in enumerate(pick, 1):
            it = items[i]
            ko = by.get((i, "paper10"), {})
            out += [f"### {n}. {i} (word {it['word']}: start {it['start']}, final {it['final']}; relation {it['relation']}; bridge {it['bridge']})", "",
                    "```", it["context"], "", it["question"], "```", "",
                    f"- Expected: **{it['answer']}**. Right unedited: yes. Right under the J++ removal: **{'yes' if ko.get('correct') else 'no'}**.", ""]  # fmt: skip
    (ROOT / "docs" / "verify_kit.md").write_text("\n".join(out) + "\n")
    print(f"wrote docs/verify_kit.md ({len(specs)} runs)")


if __name__ == "__main__":
    main(sys.argv[1:])
